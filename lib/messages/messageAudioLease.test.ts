import { PGlite } from '@electric-sql/pglite';
import { createClient, type SupabaseClient } from '@supabase/supabase-js';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
vi.mock('server-only', () => ({}));
import { claimMessageAudioLease } from './messageAudioLease';

const id = 'ad4985af-0789-4927-ad14-5e21f5ec5660';
const token = '3fec229c-724d-498d-b5c7-f53196f36051';
const competitor = '593e330f-9886-43ea-ab93-c26934d38938';
const now = new Date('2026-11-01T19:00:00.000Z');
const expiry = '2026-11-01T19:10:00.000Z';

describe('message audio claims through Supabase requests', () => {
    let db: PGlite;
    let requests: URL[];
    let client: SupabaseClient;

    beforeEach(async () => {
        db = new PGlite();
        requests = [];
        await db.exec('CREATE TABLE messages (id uuid PRIMARY KEY, audio_generation_token uuid, audio_generation_until timestamptz, audio jsonb)');
        await db.query('INSERT INTO messages (id,audio) VALUES ($1,$2)', [id, { key: 'existing.mp3' }]);
        // Execute real SQL behind the serialized HTTP requests. For OR mutations, reproduce the extra SELECT
        // predicate generated by affected PostgREST versions: https://github.com/PostgREST/postgrest/issues/3707.
        const fetch: typeof globalThis.fetch = async (input, init) => {
            const url = new URL(String(input));
            requests.push(url);
            expect(init?.method).toBe('PATCH');
            const body = JSON.parse(String(init?.body));
            const columns = (url.searchParams.get('select') || '').split(',');
            expect(columns.every((column) => ['id', 'audio_generation_until'].includes(column))).toBe(true);
            const or = url.searchParams.get('or');
            const filter = url.searchParams.get('audio_generation_until');
            const cutoff = or ? or.match(/audio_generation_until\.lt\.([^)]*)/)?.[1] : filter?.slice(3);
            const condition = or
                ? '(audio_generation_until IS NULL OR audio_generation_until < $4::timestamptz)'
                : filter === 'is.null' ? 'audio_generation_until IS NULL' : 'audio_generation_until < $4::timestamptz';
            const update = `UPDATE messages SET audio_generation_token=$1::uuid,audio_generation_until=$2::timestamptz
                WHERE id=$3::uuid AND ${condition} RETURNING ${columns.join(',')}`;
            const sql = or ? `WITH pgrst_source AS (${update}) SELECT * FROM pgrst_source AS messages
                WHERE messages.audio_generation_until IS NULL OR messages.audio_generation_until < $4::timestamptz` : update;
            const values = [body.audio_generation_token, body.audio_generation_until, url.searchParams.get('id')?.slice(3)];
            if (or || filter !== 'is.null') values.push(cutoff);
            try {
                const { rows } = await db.query(sql, values);
                return rows.length ? Response.json(rows[0]) : Response.json({
                    code: 'PGRST116', details: 'The result contains 0 rows', message: 'JSON object requested, multiple (or no) rows returned',
                }, { status: 406 });
            } catch (error) {
                const failure = error as { code: string; message: string };
                return Response.json({ code: failure.code, message: failure.message }, { status: 400 });
            }
        };
        client = createClient('https://database.example.test', 'test-only-key', {
            global: { fetch }, auth: { persistSession: false, autoRefreshToken: false },
        });
    });

    afterEach(async () => { await db.close(); });

    it('reproduces 42703 from the legacy OR query even though the database column exists', async () => {
        const result = await client.from('messages').update({ audio_generation_token: token, audio_generation_until: expiry })
            .eq('id', id).or(`audio_generation_until.is.null,audio_generation_until.lt.${now.toISOString()}`).select('id').maybeSingle();
        expect(result.error?.code).toBe('42703');
        expect((await db.query('SELECT audio_generation_until FROM messages')).rows).toEqual([{ audio_generation_until: null }]);
    });

    it('shows why adding the expiry to SELECT alone still hides a successful legacy claim', async () => {
        const result = await client.from('messages').update({ audio_generation_token: token, audio_generation_until: expiry })
            .eq('id', id).or(`audio_generation_until.is.null,audio_generation_until.lt.${now.toISOString()}`)
            .select('id,audio_generation_until').maybeSingle();
        expect(result.error).toBeNull();
        expect(result.data).toBeNull();
        expect((await db.query('SELECT audio_generation_token FROM messages')).rows).toEqual([{ audio_generation_token: token }]);
    });

    it.each([null, '2026-11-01T18:59:00.000Z'])('claims a free or expired lease (%s) and preserves the recording', async (previousExpiry) => {
        await db.query('UPDATE messages SET audio_generation_until=$1::timestamptz', [previousExpiry]);
        await claimMessageAudioLease(client, id, token, now);
        expect((await db.query('SELECT audio_generation_token,audio FROM messages')).rows)
            .toEqual([{ audio_generation_token: token, audio: { key: 'existing.mp3' } }]);
        expect(requests).toHaveLength(previousExpiry ? 2 : 1);
        expect(requests.every((request) => !request.searchParams.has('or'))).toBe(true);
    });

    it('keeps a live lease owned by another caller', async () => {
        await db.query('UPDATE messages SET audio_generation_token=$1::uuid,audio_generation_until=$2::timestamptz', [competitor, expiry]);
        await expect(claimMessageAudioLease(client, id, token, now)).rejects.toMatchObject({ status: 409 });
        expect((await db.query('SELECT audio_generation_token FROM messages')).rows).toEqual([{ audio_generation_token: competitor }]);
    });

    it.each([null, '2026-11-01T18:59:00.000Z'])('allows exactly one simultaneous claimant (%s)', async (previousExpiry) => {
        await db.query('UPDATE messages SET audio_generation_until=$1::timestamptz', [previousExpiry]);
        const results = await Promise.allSettled([
            claimMessageAudioLease(client, id, token, now), claimMessageAudioLease(client, id, competitor, now),
        ]);
        expect(results.filter((result) => result.status === 'fulfilled')).toHaveLength(1);
        expect(results.filter((result) => result.status === 'rejected')).toMatchObject([{ reason: { status: 409 } }]);
    });
});
