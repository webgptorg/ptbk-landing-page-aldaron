import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createInternalOneTimePayment, createOneTimePaymentQuote, STRIPE_CZK_PAYMENT_POLICY } from './paymentCollectionPolicy';

describe('private internal one-time payment ledger in PostgreSQL', () => {
    let db: PGlite;
    beforeAll(async () => {
        db = new PGlite();
        await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
            CREATE TABLE public."Contact" (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                fullname text, email text, "placeName" text, "isWaitlisted" boolean, "userNote" text);
            GRANT ALL ON public."Contact" TO service_role;
            GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
            INSERT INTO public."Contact"(fullname,"userNote") VALUES('Historical buyer','historical order');`);
        await db.exec(readFileSync(new URL('../../migrations/2026-11-1820-internal-one-time-payments.sql', import.meta.url), 'utf8'));
    }, 15000);
    afterAll(async () => { await db?.close(); });
    const insert = async (amount: number, overrides: Record<string, unknown> = {}, waitlisted = false) => {
        const payment = { ...createInternalOneTimePayment(createOneTimePaymentQuote(amount, STRIPE_CZK_PAYMENT_POLICY)), ...overrides };
        const purchase = { registrationType: 'AI_SUPERVIZE_MINI_WORKSHOP_REGISTRATION', selectedDateId: 'workshop',
            computedFinalPriceCzk: amount / 100, billingDetails: 'Frozen billing address', discountSnapshot: { version: 1, finalAmount: amount } };
        const result = await db.query<{ id: number }>(`INSERT INTO public."Contact"(fullname,email,"placeName","isWaitlisted","userNote","oneTimePayment")
            VALUES('Jana','jana@example.com','AiSupervizeMiniWorkshopRegistration',$1,$2,$3) RETURNING id`,
            [waitlisted, JSON.stringify(purchase), JSON.stringify(payment)]);
        return { contactId: result.rows[0]!.id, payment };
    };
    it('does not backfill or reinterpret historical registrations', async () => {
        expect((await db.query('SELECT "oneTimePayment" FROM "Contact" WHERE id=1')).rows[0]).toEqual({ oneTimePayment: null });
    });
    it.each([0, 100, 1499])('atomically records a paid %i-haléř offer with a zero cash receipt and frozen invoice input', async (amount) => {
        await db.exec('SET ROLE service_role');
        try {
            const { contactId, payment } = await insert(amount);
            const row = (await db.query('SELECT * FROM internal_purchase_payments WHERE contact_id=$1', [contactId])).rows[0];
            expect(row).toMatchObject({ status: 'paid', amount_before_waiver: amount, amount_paid: 0, amount_due: 0, waived_amount: amount,
                buyer_snapshot: { email: 'jana@example.com', billingDetails: 'Frozen billing address' },
                purchase_snapshot: { discountSnapshot: { finalAmount: amount } }, receipt: payment });
        } finally { await db.exec('RESET ROLE'); }
    });
    it('retains receipts and billing evidence after the contact is edited or deleted', async () => {
        const { contactId } = await insert(100);
        await db.query('UPDATE "Contact" SET "userNote"=$1,email=$2 WHERE id=$3', ['edited', 'other@example.com', contactId]);
        await db.query('DELETE FROM "Contact" WHERE id=$1', [contactId]);
        expect((await db.query('SELECT buyer_snapshot,purchase_snapshot FROM internal_purchase_payments WHERE contact_id=$1', [contactId])).rows[0])
            .toMatchObject({ buyer_snapshot: { email: 'jana@example.com' }, purchase_snapshot: { computedFinalPriceCzk: 1 } });
    });
    it('rejects a fabricated payment and rolls back the registration if the receipt cannot be recorded', async () => {
        const before = (await db.query('SELECT count(*) FROM "Contact"')).rows[0];
        await expect(insert(100, { amountPaid: 100 })).rejects.toThrow();
        await expect(insert(100, { amountBeforeWaiver: 1500, waivedAmount: 1500 })).rejects.toThrow();
        await expect(insert(100, {}, true)).rejects.toThrow();
        expect((await db.query('SELECT count(*) FROM "Contact"')).rows[0]).toEqual(before);
    });
    it('blocks editing accepted receipts and keeps all ledger data private', async () => {
        const { contactId } = await insert(100);
        await expect(db.query('UPDATE "Contact" SET "oneTimePayment"=NULL WHERE id=$1', [contactId])).rejects.toThrow('immutable');
        await expect(db.query('DELETE FROM internal_purchase_payments WHERE contact_id=$1', [contactId])).rejects.toThrow('immutable');
        for (const role of ['anon', 'authenticated']) {
            expect((await db.query("SELECT has_table_privilege($1,'public.internal_purchase_payments','SELECT') AS allowed", [role])).rows[0]).toEqual({ allowed: false });
        }
        expect((await db.query("SELECT has_table_privilege('service_role','public.internal_purchase_payments','INSERT') AS allowed")).rows[0]).toEqual({ allowed: false });
    });
});
