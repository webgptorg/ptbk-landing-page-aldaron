/** @vitest-environment jsdom */
import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import '@testing-library/jest-dom/vitest';
const mocks = vi.hoisted(() => ({ request: vi.fn(), transcribe: vi.fn() }));
vi.mock('@/lib/admin/requestAdminJson', () => ({ requestAdminJson: mocks.request }));
vi.mock('@/lib/messages/messageTranscriptionClient', () => ({ transcribeMessageFile: mocks.transcribe }));
vi.mock('./MessageMeetingRecorder', () => ({ MessageMeetingRecorder: () => null }));
import { MessageEditor } from './MessageEditor';
import { TEST_MESSAGE } from '@/lib/messages/messageTestFixtures';
const agent = { id: TEST_MESSAGE.agentId, name: 'Pavol Hejný', isEnabled: true };
afterEach(() => { cleanup(); vi.resetAllMocks(); });
describe('two-step message editor', () => {
    it('adopts prepared server links without replacing text typed while the save was pending', async () => {
        let complete!: (value: unknown) => void;
        const raw = 'Viz https://example.com/doc';
        const prepared = 'Viz [Dokument](https://ptbk.io/AbCd1234)';
        mocks.request.mockReturnValueOnce(new Promise((resolve) => { complete = resolve; }));
        mocks.request.mockResolvedValue({ message: { ...TEST_MESSAGE, markdown: 'Novější text.' } });
        render(<MessageEditor message={TEST_MESSAGE} agents={[agent]} audioConfigured={false} transcriptionConfigured={false} onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Krátká zpráva'), { target: { value: raw } });
        await waitFor(() => expect(mocks.request).toHaveBeenCalledOnce(), { timeout: 2000 });
        fireEvent.change(screen.getByLabelText('Krátká zpráva'), { target: { value: 'Novější text.' } });
        complete({ message: { ...TEST_MESSAGE, markdown: prepared } });
        await waitFor(() => expect(mocks.request).toHaveBeenCalledTimes(2));
        expect(screen.getByLabelText('Krátká zpráva')).toHaveValue('Novější text.');
        const options = mocks.request.mock.calls[1][1] as { body: string };
        const body = JSON.parse(options.body) as { markdown: string };
        expect(body.markdown).toBe('Novější text.');
    });
    it('shows server-prepared links in both the editable draft and share text', async () => {
        const prepared = 'Viz [Dokument](https://ptbk.io/AbCd1234)';
        mocks.request.mockResolvedValue({ message: { ...TEST_MESSAGE, markdown: prepared } });
        render(<MessageEditor message={TEST_MESSAGE} agents={[agent]} audioConfigured={false} transcriptionConfigured={false} onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Krátká zpráva'), { target: { value: 'Viz https://example.com/doc' } });
        await waitFor(() => expect(screen.getByLabelText('Krátká zpráva')).toHaveValue(prepared), { timeout: 2000 });
        expect((screen.getByLabelText('Zpráva k odeslání včetně odkazu') as HTMLTextAreaElement).value).toContain(prepared);
    });
    it('generates three texts only on request, keeps the draft editable and requires explicit creation', async () => {
        mocks.request.mockResolvedValueOnce({ title: 'První použití', markdown: 'Ahoj týme,\n\nDokončíme registraci.', introduction: 'Můžeme probrat první použití.' });
        const saved = vi.fn();
        render(<MessageEditor message={null} agents={[agent]} audioConfigured={false} transcriptionConfigured={false} onSaved={saved} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Celý kontext'), { target: { value: 'The intended decision and full reasoning.' } });
        expect(mocks.request).not.toHaveBeenCalled();
        fireEvent.click(screen.getByRole('button', { name: 'Vygenerovat a pokračovat' }));
        expect(await screen.findByLabelText('Titulek')).toHaveValue('První použití');
        expect(screen.getByLabelText('Prefix adresy')).toHaveValue('prvni-pouziti');
        expect(screen.getByLabelText('Úvodní zpráva chatu')).toHaveValue('Můžeme probrat první použití.');
        expect(saved).not.toHaveBeenCalled();
        expect(mocks.request).toHaveBeenCalledTimes(1);
        mocks.request.mockResolvedValueOnce({ message: TEST_MESSAGE });
        fireEvent.click(screen.getByRole('button', { name: 'Vytvořit zprávu' }));
        await waitFor(() => expect(saved).toHaveBeenCalledWith(TEST_MESSAGE));
        expect(mocks.request.mock.calls[1][0]).toBe('/api/admin/messages');
        expect(mocks.request.mock.calls.some(([url]) => String(url).endsWith('/audio'))).toBe(false);
    });
    it('keeps authored text when explicit regeneration fails', async () => {
        mocks.request.mockRejectedValueOnce(new Error('Generation unavailable.'));
        render(<MessageEditor message={TEST_MESSAGE} agents={[agent]} audioConfigured={false} transcriptionConfigured={false} onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.click(screen.getByRole('button', { name: 'Přegenerovat texty' }));
        expect(await screen.findByRole('alert')).toHaveTextContent('Generation unavailable.');
        expect(screen.getByLabelText('Krátká zpráva')).toHaveValue(TEST_MESSAGE.markdown);
    });
    it('autosaves existing text without publishing controls or automatically generating speech', async () => {
        mocks.request.mockResolvedValue({ message: { ...TEST_MESSAGE, markdown: 'Updated decision.' } });
        render(<MessageEditor message={TEST_MESSAGE} agents={[agent]} audioConfigured transcriptionConfigured onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Krátká zpráva'), { target: { value: 'Updated decision.' } });
        await waitFor(() => expect(mocks.request).toHaveBeenCalledTimes(1), { timeout: 2000 });
        expect(mocks.request.mock.calls[0][0]).toBe(`/api/admin/messages/${TEST_MESSAGE.id}`);
        const body = JSON.parse(mocks.request.mock.calls[0][1].body) as { context: string; markdown: string };
        expect(body.context).toBe(TEST_MESSAGE.context); expect(body.markdown).toBe('Updated decision.');
        expect(screen.queryByRole('button', { name: /Publikovat/ })).toBeNull();
    });
    it('inserts an audio transcript into the editable context and sends it through the existing explicit summary flow', async () => {
        const transcript = 'Následuje přepsané audio: Schůzka.m4a\n\nMluvčí 1:\nDokončíme registraci.';
        mocks.transcribe.mockResolvedValueOnce(transcript);
        render(<MessageEditor message={null} agents={[agent]} audioConfigured={false} transcriptionConfigured onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Celý kontext'), { target: { value: 'Moje další poznámky.' } });
        fireEvent.change(screen.getByLabelText('Audio soubor'), { target: { files: [new File(['audio'], 'Schůzka.m4a', { type: 'audio/mp4' })] } });
        const context = `Moje další poznámky.\n\n${transcript}`;
        await waitFor(() => expect(screen.getByLabelText('Celý kontext')).toHaveValue(context));
        expect(mocks.request).not.toHaveBeenCalled();
        expect(screen.queryByLabelText('Titulek')).toBeNull();
        mocks.request.mockResolvedValueOnce({ title: 'Registrace', markdown: 'Dokončíme registraci.', introduction: 'Proberme registraci.' });
        fireEvent.click(screen.getByRole('button', { name: 'Vygenerovat a pokračovat' }));
        await screen.findByLabelText('Titulek');
        expect(mocks.request).toHaveBeenCalledOnce();
        expect(JSON.parse(mocks.request.mock.calls[0][1].body)).toEqual({ context, agentId: agent.id });
    });
    it('preserves authored context after a failed upload and retries only when requested', async () => {
        mocks.transcribe.mockRejectedValueOnce(new Error('Provider unavailable.'));
        render(<MessageEditor message={null} agents={[agent]} audioConfigured={false} transcriptionConfigured onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Celý kontext'), { target: { value: 'Původní kontext.' } });
        const file = new File(['audio'], 'Meeting.m4a');
        fireEvent.change(screen.getByLabelText('Audio soubor'), { target: { files: [file] } });
        expect(await screen.findByRole('alert')).toHaveTextContent('Provider unavailable.');
        expect(screen.getByLabelText('Celý kontext')).toHaveValue('Původní kontext.');
        expect(mocks.transcribe).toHaveBeenCalledOnce();
        mocks.transcribe.mockResolvedValueOnce('Následuje přepsané audio: Meeting.m4a\n\nVýsledek.');
        fireEvent.click(screen.getByRole('button', { name: 'Zkusit přepis znovu' }));
        await waitFor(() => expect(screen.getByLabelText('Celý kontext')).toHaveValue('Původní kontext.\n\nNásleduje přepsané audio: Meeting.m4a\n\nVýsledek.'));
        expect(mocks.transcribe).toHaveBeenCalledTimes(2); expect(mocks.request).not.toHaveBeenCalled();
    });
    it('accepts drag and drop once, blocks overlapping transcription and keeps summary narration independent', async () => {
        let finish!: (value: string) => void;
        mocks.transcribe.mockImplementationOnce(() => new Promise<string>((resolve) => { finish = resolve; }));
        const busy = vi.fn();
        mocks.request.mockResolvedValue({ message: TEST_MESSAGE });
        render(<MessageEditor message={TEST_MESSAGE} agents={[agent]} audioConfigured transcriptionConfigured onSaved={() => undefined} onBusy={busy} />);
        fireEvent.click(screen.getByRole('button', { name: '1. Celý kontext' }));
        fireEvent.click(screen.getByRole('button', { name: 'Importovat audio soubor' }));
        const dropzone = screen.getByRole('region', { name: 'Kontext z audia' });
        const dataTransfer = { files: [new File(['audio'], 'Call.mp3')] };
        fireEvent.drop(dropzone, { dataTransfer }); fireEvent.drop(dropzone, { dataTransfer });
        expect(mocks.transcribe).toHaveBeenCalledOnce();
        expect(screen.getByLabelText('Celý kontext')).toBeDisabled();
        expect(busy).toHaveBeenLastCalledWith(true);
        finish('Následuje přepsané audio: Call.mp3\n\nPoznámky.');
        await waitFor(() => expect(screen.getByLabelText('Celý kontext')).toHaveValue(`${TEST_MESSAGE.context}\n\nNásleduje přepsané audio: Call.mp3\n\nPoznámky.`));
        expect(busy).toHaveBeenLastCalledWith(false);
        await waitFor(() => expect(mocks.request).toHaveBeenCalledOnce(), { timeout: 2000 });
        const body = JSON.parse(mocks.request.mock.calls[0][1].body) as { markdown: string; context: string };
        expect(body.markdown).toBe(TEST_MESSAGE.markdown); expect(body.context).toContain('Call.mp3');
        expect(mocks.request.mock.calls[0][0]).toBe(`/api/admin/messages/${TEST_MESSAGE.id}`);
    });
    it('retains a completed transcript for manual recovery if the combined context is too long', async () => {
        const original = 'a'.repeat(1_500_000);
        const transcript = 'Následuje přepsané audio: meeting.m4a\n\nDokončený přepis.';
        mocks.transcribe.mockResolvedValueOnce(transcript);
        render(<MessageEditor message={null} agents={[agent]} audioConfigured={false} transcriptionConfigured onSaved={() => undefined} onBusy={() => undefined} />);
        fireEvent.change(screen.getByLabelText('Celý kontext'), { target: { value: original } });
        fireEvent.change(screen.getByLabelText('Audio soubor'), { target: { files: [new File(['audio'], 'meeting.m4a')] } });
        expect(await screen.findByRole('alert')).toHaveTextContent('Zkraťte kontext');
        expect(screen.getByLabelText('Dokončený přepis')).toHaveValue(transcript);
        expect(screen.getByLabelText('Celý kontext')).toHaveValue(original);
        fireEvent.change(screen.getByLabelText('Celý kontext'), { target: { value: 'Kratší poznámky.' } });
        fireEvent.click(screen.getByRole('button', { name: 'Přidat přepis do kontextu' }));
        await waitFor(() => expect(screen.queryByLabelText('Dokončený přepis')).toBeNull());
        expect(screen.getByLabelText('Celý kontext')).toHaveValue(`Kratší poznámky.\n\n${transcript}`);
        expect(mocks.transcribe).toHaveBeenCalledOnce();
    });
});
